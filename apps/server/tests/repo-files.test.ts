import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, test } from 'vitest'
import { LIB_ALLOWLIST } from '../../../eslint.config.mjs'
import { repoRoot } from './helpers/comments'

const tracked = execFileSync('git', ['ls-files', '-z'], {
  cwd: repoRoot,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
})
  .split('\0')
  .filter(Boolean)
const read = (file: string) => readFileSync(join(repoRoot, file), 'utf8')
const lineCount = (file: string) => read(file).replace(/\n$/, '').split('\n').length

const ROOT_MARKDOWN = [
  'README.md',
  'CONTEXT.md',
  'DESIGN.md',
  'CONTRIBUTING.md',
  'SECURITY.md',
  'CHANGELOG.md',
  'AGENTS.md',
  'REVIEW.md',
]
const MARKDOWN_ALLOWED = [
  (f: string) => ROOT_MARKDOWN.includes(f),
  (f: string) => /^(docs|pack|\.github)\//.test(f),
  (f: string) => /^(apps|packages)\/[^/]+\/README\.md$/.test(f),
]

const GENERATED_MARKER = /generated by|do not edit|@generated|auto-?generated/i
const NOT_TEXT = /\.(png|jpe?g|gif|webp|ico|woff2?|ttf|pdf|lock)$/
const GENERATED_EXCEPTIONS: { file: string; reason: string }[] = []

const MARKDOWN_HELP =
  'Markdown lives in README.md, CONTEXT.md, DESIGN.md, CONTRIBUTING.md, SECURITY.md, CHANGELOG.md, ' +
  'AGENTS.md or REVIEW.md at the root, in docs/, pack/ or .github/, or as README.md directly in a package or app. ' +
  'Put agent rules in AGENTS.md or pack/rules, product text in docs/, ' +
  'and explanations of code in a name, a type or a test.'

test('markdown exists only at the listed places', () => {
  const stray = tracked.filter((f) => /\.mdx?$/.test(f) && !MARKDOWN_ALLOWED.some((ok) => ok(f)))
  expect(stray, MARKDOWN_HELP).toEqual([])
})

test('AGENTS.md has at most 60 lines', () => {
  const lines = tracked.includes('AGENTS.md') ? lineCount('AGENTS.md') : 0
  expect(
    lines,
    'AGENTS.md holds only judgment rules that no check enforces. ' +
      'Delete what lint or a test already enforces, or move detail into docs/.',
  ).toBeLessThanOrEqual(60)
})

test('a file under pack/ has at most 100 lines', () => {
  const long = tracked.filter((f) => f.startsWith('pack/')).filter((f) => lineCount(f) > 100)
  expect(long, 'Split the file under pack/ by topic, or cut it: an agent reads all of it on every run.').toEqual([])
})

test('no tracked file says it is generated', () => {
  const generated = tracked
    .filter((f) => !GENERATED_EXCEPTIONS.some((e) => e.file === f))
    .filter((f) => !NOT_TEXT.test(f) && f !== 'pnpm-lock.yaml')
    .filter((f) => read(f).split('\n').slice(0, 5).some((l) => GENERATED_MARKER.test(l)))
  expect(
    generated,
    'Do not commit generated files. Git-ignore the file and generate it in the build and test scripts, ' +
      'as migrations/index.ts and tokens.css are.',
  ).toEqual([])
})

test('every generated-file exception states its reason', () => {
  expect(GENERATED_EXCEPTIONS.filter((e) => e.reason.length < 20)).toEqual([])
})

test('the strict compiler project includes exactly the allowlisted lib files', () => {
  const { include } = JSON.parse(read('apps/server/tsconfig.core.json')) as { include: string[] }
  const strictLib = include.filter((f) => f.startsWith('src/lib/')).sort()
  const allowed = LIB_ALLOWLIST.map((name) => `src/lib/${name}.ts`).sort()
  expect(
    strictLib,
    'LIB_ALLOWLIST in eslint.config.mjs and the src/lib entries in apps/server/tsconfig.core.json ' +
      'must list the same files. ' +
      'Fix the strict errors in a file before you allow it, and remove a file from both when it cannot pass.',
  ).toEqual(allowed)
})

test('every path in the Enforced by column of docs/references.md exists', () => {
  const rows = read('docs/references.md').split('\n').filter((l) => l.startsWith('|')).slice(2)
  const paths = rows.flatMap((row) => [...(row.split('|')[3] ?? '').matchAll(/`([^`]+)`/g)].map((m) => m[1] ?? ''))
  const missing = paths.filter((p) => !existsSync(join(repoRoot, p)))
  expect(
    missing,
    'docs/references.md names a file that does not exist in the Enforced by column. ' +
      'Fix the path, or remove the row when no file enforces the practice any more.',
  ).toEqual([])
  expect(paths.length).toBeGreaterThan(0)
})
