import { createHash } from 'node:crypto'
import { stageLabel } from '@bauherr/adapters'
import type { Stage } from '../events'
import { LabelOutsideNamespace } from './errors'

export const DISCLOSURE = '_AI-generated by Bauherr. Not a maintainer decision._'
export const NAMESPACE = 'bauherr:'
export const STAGE_PREFIX = `${NAMESPACE}stage:`

export const disclosed = (body: string): string => {
  const text = body.trim()
  const rest = text.startsWith(DISCLOSURE) ? text.slice(DISCLOSURE.length).trim() : text
  return `${DISCLOSURE}\n\n${rest}`
}

export const hashBody = (body: string): string => createHash('sha256').update(body).digest('hex')

export type LabelPlan = { add: string[]; remove: string[]; next: string[] }

export const assertNamespaced = (labels: string[]): void => {
  const outside = labels.find((label) => !label.startsWith(NAMESPACE))
  if (outside !== undefined) {
    throw new LabelOutsideNamespace(`Label ${outside} is not in the ${NAMESPACE} namespace: Bauherr never touches it.`)
  }
}

export const planStageLabels = (current: string[], stage: Stage): LabelPlan => {
  const wanted = stageLabel(stage)
  const add = current.includes(wanted) ? [] : [wanted]
  const remove = current.filter((label) => label.startsWith(STAGE_PREFIX) && label !== wanted)
  assertNamespaced([...add, ...remove])
  const next = [...current.filter((label) => !remove.includes(label)), ...add]
  return { add, remove, next }
}
