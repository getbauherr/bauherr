import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { email } from './user'

const PIXEL = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==',
  'base64',
)

const signIn = async (page: Page) => {
  const url = process.env.BASE_URL ?? 'http://localhost:3000'
  await page.context().addCookies([{ name: 'bauherr-ws', value: 'requests', url }])
  await page.goto('/login')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password').fill(readFileSync(process.env.E2E_PASSWORD_FILE!, 'utf8').trim())
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('banner')).toBeVisible()
}

const issuesOf = (page: Page) =>
  page.evaluate(async () => {
    const res = await fetch('/api/fake-forge?repo=requests/app')
    return ((await res.json()) as { issues: { body: string }[] }).issues
  })

const dropFile = (page: Page, name: string) =>
  page.evaluate((fileName) => {
    const zone = document.querySelector('[data-slot="aui_composer-shell"]')!
    const transfer = new DataTransfer()
    transfer.items.add(new File(['Notes about the export.'], fileName, { type: 'text/plain' }))
    zone.dispatchEvent(new DragEvent('drop', { dataTransfer: transfer, bubbles: true, cancelable: true }))
  }, name)

test('@fake-forge a request is written to the issue tracker only when it is sent, with its files', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await signIn(page)
  await page.goto('/requests/new')
  const card = page.getByLabel('Your request')

  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Add attachment' }).click()
  await (await chooser).setFiles({ name: 'export-koeln.png', mimeType: 'image/png', buffer: PIXEL })
  await expect(card.getByText('export-koeln.png')).toBeVisible()
  await dropFile(page, 'drop-notes.txt')
  await expect(card.getByText('drop-notes.txt')).toBeVisible()

  await page
    .getByRole('textbox', { name: 'Describe your request' })
    .fill('The export of our CO2 balance breaks for the big cities, it just stops.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByTestId('request-questions')).toBeVisible()
  await expect(card.getByText('Something is broken (bug)')).toBeVisible()
  await expect(card.getByText(/Still missing: .*How often/)).toBeVisible()
  expect(await issuesOf(page)).toHaveLength(0)

  await page.getByRole('button', { name: 'Accept every suggestion' }).click()
  await expect(card.getByText('Complete: you can send it.')).toBeVisible()
  await card.getByRole('button', { name: 'Send request' }).click()
  await expect(card.getByText(/Sent as issue #\d+/)).toBeVisible()
  await page.screenshot({ path: 'e2e/results/request-card.png' })

  const issues = await issuesOf(page)
  expect(issues).toHaveLength(1)
  expect(issues[0]!.body.startsWith('_AI-generated by Bauherr. Not a maintainer decision._')).toBe(true)
  expect(issues[0]!.body).toContain('export-koeln.png')
  expect(issues[0]!.body).toContain('drop-notes.txt')
})
