import { readFileSync, writeFileSync } from 'node:fs'
import { parseTokens } from './design-tokens'

const t = parseTokens(readFileSync(new URL('../../../docs/design/tokens.json', import.meta.url), 'utf8'))

const ref = (v: string) => v.replace(/^\{(.+)\}$/, 'var(--$1)')
const colors = t.color.tokens
const decl = (theme: 'light' | 'dark') =>
  colors.map((c) => `--${c.name}:${ref(typeof c.value === 'string' ? c.value : c.value[theme])};`).join('')
const plain = [...t.spacing.tokens, ...t.radius.tokens, ...t.duration.tokens, ...t.easing.tokens]
const fonts = Object.entries(t.type.families)
  .map(([k, v]) => `--font-${k}:${v};`)
  .join('')
const styles = t.type.groups.flatMap((g) =>
  g.styles.map((s) => {
    const letterSpacing = s.letterSpacing ? `letter-spacing:${s.letterSpacing};` : ''
    const transform = s.name === 'label' ? 'text-transform:uppercase;' : ''
    const numerals = s.name === 'mono' ? 'font-variant-numeric:tabular-nums;' : ''
    return (
      `@utility ${s.name}{font-family:var(--font-${g.family});font-size:${s.fontSize};line-height:${s.lineHeight};` +
      `font-weight:${s.fontWeight};${letterSpacing}${transform}${numerals}}`
    )
  }),
)

const darkSelector = ':root:not([data-theme="light"]):not([data-theme="dark"])'

const css = `/* Generated by scripts/tokens.ts from docs/design/tokens.json. Do not edit. */
:root{${decl('light')}${plain.map((p) => `--${p.name}:${p.value as string};`).join('')}${fonts}color-scheme:light}
:root[data-theme="dark"]{${decl('dark')}color-scheme:dark}
@media (prefers-color-scheme:dark){${darkSelector}{${decl('dark')}color-scheme:dark}}
@media (prefers-reduced-motion:reduce){:root{${t.duration.tokens.map((d) => `--${d.name}:0ms;`).join('')}}}
`
const utilities = `/* Generated by scripts/tokens.ts from docs/design/tokens.json. Do not edit. */
${styles.join('\n')}
`
writeFileSync(new URL('../src/app/(app)/tokens.css', import.meta.url), css)
writeFileSync(new URL('../src/app/(app)/typography.css', import.meta.url), utilities)
