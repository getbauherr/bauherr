import { readFileSync, writeFileSync } from 'node:fs'

type Tok = { name: string; value: string | { light: string; dark: string } }
type Style = { name: string; fontSize: string; lineHeight: string; fontWeight: number; letterSpacing?: string }
const t = JSON.parse(readFileSync(new URL('../../../docs/design/tokens.json', import.meta.url), 'utf8'))

const ref = (v: string) => v.replace(/^\{(.+)\}$/, 'var(--$1)')
const colors: Tok[] = t.color.tokens
const decl = (theme: 'light' | 'dark') =>
  colors.map((c) => `--${c.name}:${ref(typeof c.value === 'string' ? c.value : c.value[theme])};`).join('')
const plain = [...t.spacing.tokens, ...t.radius.tokens, ...t.duration.tokens, ...t.easing.tokens] as Tok[]
const fonts = Object.entries(t.type.families as Record<string, string>).map(([k, v]) => `--font-${k}:${v};`).join('')
const styles = (t.type.groups as { family: string; styles: Style[] }[]).flatMap((g) =>
  g.styles.map(
    (s) =>
      `.${s.name}{font-family:var(--font-${g.family});font-size:${s.fontSize};line-height:${s.lineHeight};font-weight:${s.fontWeight};${s.letterSpacing ? `letter-spacing:${s.letterSpacing};` : ''}${s.name === 'label' ? 'text-transform:uppercase;' : ''}${s.name === 'mono' ? 'font-variant-numeric:tabular-nums;' : ''}}`,
  ),
)

const css = `/* Generated by scripts/tokens.ts from docs/design/tokens.json. Do not edit. */
:root{${decl('light')}${plain.map((p) => `--${p.name}:${p.value as string};`).join('')}${fonts}color-scheme:light}
:root[data-theme="dark"]{${decl('dark')}color-scheme:dark}
@media (prefers-color-scheme:dark){:root:not([data-theme="light"]):not([data-theme="dark"]){${decl('dark')}color-scheme:dark}}
@media (prefers-reduced-motion:reduce){:root{--duration-state:0ms;--duration-panel:0ms;--duration-page:0ms}}
${styles.join('\n')}
`
writeFileSync(new URL('../src/app/(app)/tokens.css', import.meta.url), css)
